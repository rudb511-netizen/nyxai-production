const TONEABLE = /^(👋|🤚|🖐️|✋|🖖|👌|🤌|🤏|✌️|🤞|🤟|🤘|🤙|👈|👉|👆|🖕|👇|☝️|👍|👎|✊|👊|🤛|🤜|👏|🙌|👐|🤲|🙏|✍️|💅|🤳|💪|🦵|🦶|👂|👃|👶|🧒|👦|👧|🧑|👱|👨|🧔|👩|🧓|👴|👵|🙍|🙎|🙅|🙆|💁|🙋|🧏|🙇|🤦|🤷)$/;

function applyTone(emoji: string, tone: string) {
  if (!tone || !TONEABLE.test(emoji)) return emoji;
  return emoji + tone;
}

function loadRecent(): string[] {
  try {
    const raw = localStorage.getItem(RECENT_KEY);
    const arr = raw ? (JSON.parse(raw) as unknown) : [];
    return Array.isArray(arr) ? arr.filter((x) => typeof x === "string").slice(0, 24) : [];
  } catch {
    return [];
  }
}

export function EmojiPicker({
  onPick,
  className,
}: {
  onPick: (emoji: string) => void;
  className?: string;
}) {
  const [tab, setTab] = useState(GROUPS[0]!.id);
  const [q, setQ] = useState("");
  const [tone, setTone] = useState(() => {
    try {
      return localStorage.getItem(TONE_KEY) ?? "";
    } catch {
      return "";
    }
  });
  const [recent, setRecent] = useState(loadRecent);

  const items = useMemo(() => {
    const query = q.trim().toLowerCase();
    const source = query
      ? GROUPS.flatMap((g) => g.items)
      : tab === "recent"
        ? recent
        : (GROUPS.find((g) => g.id === tab)?.items ?? []);
    const mapped = source.map((e) => applyTone(e, tone));
    if (!query) return mapped;
    return mapped.filter((e) => e.includes(query) || e.toLowerCase().includes(query));
  }, [q, tab, tone, recent]);

  function pick(emoji: string) {
    onPick(emoji);
    const next = [emoji, ...recent.filter((r) => r !== emoji)].slice(0, 24);
    setRecent(next);
    try {
      localStorage.setItem(RECENT_KEY, JSON.stringify(next));
    } catch {
      /* ignore */
    }
  }

  return (
    <div className={cn("rounded-2xl border border-border bg-surface p-2 shadow-border", className)}>
      <input
        value={q}
        onChange={(e) => setQ(e.target.value)}
        placeholder="Search or paste emoji"
        className="mb-2 w-full rounded-xl border border-border bg-elevated px-3 py-2 text-sm"
        aria-label="Search emoji"
      />
      <div className="mb-2 flex gap-1 overflow-x-auto">
        <button
          type="button"
          className={cn("rounded-full px-2 py-1 text-[11px]", tab === "recent" ? "bg-accent text-accent-fg" : "bg-elevated text-muted")}
          onClick={() => setTab("recent")}
        >
          Recent
        </button>
        {GROUPS.map((g) => (
          <button
            key={g.id}
            type="button"
            className={cn("rounded-full px-2 py-1 text-[11px]", tab === g.id ? "bg-accent text-accent-fg" : "bg-elevated text-muted")}
            onClick={() => setTab(g.id)}
          >
            {g.label}
          </button>
        ))}
      </div>
      <div className="mb-2 flex items-center gap-1">
        <span className="text-[11px] text-muted">Tone</span>
        {TONES.map((t) => (
          <button
            key={t || "none"}
            type="button"
            className={cn("grid size-7 place-items-center rounded-full text-sm", tone === t ? "ring-2 ring-accent" : "bg-elevated")}
            onClick={() => {
              setTone(t);
              try {
                localStorage.setItem(TONE_KEY, t);
              } catch {
                /* ignore */
              }
            }}
            aria-label={t ? `Skin tone ${t}` : "Default tone"}
          >
            {`👋${t}`}
          </button>
        ))}
      </div>
      <div className="grid max-h-48 grid-cols-8 gap-0.5 overflow-y-auto">
        {items.map((e, i) => (
          <button
            key={`${e}-${i}`}
            type="button"
            className="grid size-9 place-items-center rounded-lg text-lg hover:bg-elevated"
            onClick={() => pick(e)}
          >
            {e}
          </button>
        ))}
      </div>
    </div>
  );
}
